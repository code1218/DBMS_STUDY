WHERE rating >= 4.0
ORDER BY rating DESC
LIMIT 3;

-- 시나리오 5: 사장님이 "1번 가게 메뉴 가격을 다 1000원씩 올려줘"
-- 반드시 WHERE로 가게를 특정해야 합니다!
UPDATE menus
SET price = price + 1000
WHERE restaurant_id = 1;

