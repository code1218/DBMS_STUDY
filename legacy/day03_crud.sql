-- ----------------------------------------------------------------
-- 2-1. 단건 INSERT (컬럼명 명시 버전) — 권장 방식
-- ----------------------------------------------------------------
-- 컬럼명을 직접 써주면 순서가 달라도 안전하고, 나중에 읽기도 쉽습니다.
